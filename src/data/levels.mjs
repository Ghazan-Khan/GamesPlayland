/**
 * Level data for the original GamesPlayLand parking engine.
 * All coordinates are metres. x grows right, y grows down, angles in degrees
 * (0 = facing east, 90 = facing south). Obstacles are centre-based rectangles.
 */

const CAR_COLORS = ['#e8edf4', '#8fa3b8', '#3d6ea8', '#b8483f', '#2f3b46', '#c9a227', '#5c8f6a'];

const frame = (w, h, t = 1) => [
  { x: w / 2, y: -t / 2, w: w + 2 * t, h: t },
  { x: w / 2, y: h + t / 2, w: w + 2 * t, h: t },
  { x: -t / 2, y: h / 2, w: t, h: h },
  { x: w + t / 2, y: h / 2, w: t, h: h },
];

const row = (xs, y, a, type = 'car') =>
  xs.map((x, i) => ({ x, y, a, type, color: CAR_COLORS[i % CAR_COLORS.length] }));

const bay = (x, y, a, l = 5.6, w = 2.9) => ({ x, y, a, l, w });

